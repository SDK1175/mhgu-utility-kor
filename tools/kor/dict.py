"""Korean fork: tools/kor/ui_ko.tsv -> mod/src/ko_dict.rs (sorted for the plugin's binary search).

    python3 tools/kor/dict.py

Also checks that the font (mod/assets/paperlogy-ko.ttf) has every Hangul syllable the dictionary uses; when not,
make the subset again: python3 tools/kor/font.py <Paperlogy-5Medium.ttf>.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TSV = ROOT / 'tools/kor/ui_ko.tsv'


def entries():
    out = {}
    for n, line in enumerate(TSV.read_text(encoding='utf-8').split('\n'), 1):
        if not line or line.startswith('#'):
            continue
        en, sep, ko = line.partition('\t')
        if not sep:
            raise SystemExit(f'{TSV.name}:{n}: no tab')
        if en in out and out[en] != ko:
            raise SystemExit(f'{TSV.name}:{n}: {en!r} twice')
        out[en] = ko
    for i in range(1, 21):
        out.setdefault(f'Area {i}', f'구역 {i}')
    return out


def rust(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    d = entries()
    keys = sorted(d, key=lambda s: s.encode('utf-8'))
    body = ''.join(f'    ({rust(k)}, {rust(d[k])}),\n' for k in keys)
    (ROOT / 'mod/src/ko_dict.rs').write_text(
        '//! Generated by tools/kor/dict.py from tools/kor/ui_ko.tsv: do not edit.\n'
        'pub static DICT: &[(&str, &str)] = &[\n' + body + '];\n', encoding='utf-8', newline='\n')
    used = {c for v in d.values() for c in v if 0xAC00 <= ord(c) <= 0xD7A3}
    try:
        from fontTools.ttLib import TTFont
        have = set(TTFont(ROOT / 'mod/assets/paperlogy-ko.ttf').getBestCmap())
        missing = ''.join(sorted(c for c in used if ord(c) not in have))
        if missing:
            print('not in the font subset (run tools/kor/font.py):', missing)
    except ImportError:
        pass
    print(f'ko_dict.rs: {len(keys)} entries')


if __name__ == '__main__':
    main()
