"""Korean fork: which English names in the generated data are game text, and where the game keeps them.

    python3 tools/kor/keys.py <MHGU dump folder holding romfs/>

Reads the English GMDs of your MHGU dump and the generated sources in build/generated/, and writes
build/generated/ko_keys.rs: every string literal of the generated data that is also a GMD string, with the GMD
(as the path MHXX keeps the same table under) and the string's index in it. No text of MHXX or of any patch is read
or written here: the plugin reads the Korean text from the game's own files when it runs (mod/src/ko.rs), so the
built plugin carries none of it.

Also writes build/kor/untranslated.txt: the short strings of the generated data that are not game text (labels,
categories). Those are translated by tools/kor/ui_ko.tsv.
"""
import json, re, struct, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GENERATED = ROOT / 'build/generated'
SKIP = {'ko_keys.rs', 'map_pixels.rs', 'ui_pixels.rs'}
# Name tables first: when a string is in several GMDs, the first of these that has it decides.
FIRST = ['itemData', 'weapon', 'armorSeriesData', 'skillData']

LITERAL = re.compile(r'"((?:[^"\\]|\\.)*)"')


def literals(text):
    for m in LITERAL.finditer(text):
        try:
            yield json.loads('"' + re.sub(r'\\u\{([0-9a-fA-F]+)\}', lambda u: '\\u%04x' % int(u.group(1), 16),
                                          m.group(1)) + '"')
        except ValueError:
            pass


def gmd_strings(path):
    data = path.read_bytes()
    if len(data) < 41 or data[:4] != b'GMD\0':
        return None
    labels, count, _, size, name = struct.unpack_from('<5I', data, 20)
    start = 41 + name if labels == 0 else len(data) - size
    if not 0 <= start <= len(data):
        return None
    rows = data[start:].split(b'\0')[:count]
    try:
        return [r.decode('utf-8') for r in rows]
    except UnicodeDecodeError:
        return None


def rust(s):
    return '"' + ''.join('\\\\' if c == '\\' else '\\"' if c == '"' else c if ord(c) >= 32 else '\\u{%x}' % ord(c)
                         for c in s) + '"'


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    native = Path(sys.argv[1]) / 'romfs/nativeNX'
    eng = native / 'eng'
    if not eng.is_dir():
        raise SystemExit(f'{eng}: missing')
    wanted = set()
    for f in sorted(GENERATED.glob('*.rs')):
        if f.name not in SKIP:
            wanted.update(s for s in literals(f.read_text(encoding='utf-8')) if s.strip())
    if not wanted:
        raise SystemExit('build/generated is empty: run tools/prepare.py (tools/kor/setup.sh) first')
    # The parts the plugin translates a composite string by (mod/src/ko.rs, compose): "Rathalos Cap S LV5",
    # "Basarios / Body Carve", "HR Rathalos Materials", "Arctic Ridge (N)", "Break Shell (Gravios) G1-2".
    derived = set()
    for s in wanted:
        for part in re.split(r' // | / ', s):
            part = re.sub(r' LV\d+$', '', part)
            part = re.sub(r' (?:Lv|G)\d+-\d+$', '', part)
            m = re.fullmatch(r'(?:G|HR|LR) (.+) Materials', part)
            if m:
                part = m[1]
            part = re.sub(r' \(N\)$', '', part)
            m = re.fullmatch(r'.+ \((.+)\)', part)
            if m:
                derived.add(m[1])
            derived.add(part)
    wanted |= derived

    def rank(p):
        stem = p.stem
        for i, k in enumerate(FIRST):
            if stem.startswith(k):
                return (i, str(p))
        return (len(FIRST), str(p))

    files, keys = [], {}
    for path in sorted(eng.rglob('*_eng.gmd'), key=rank):
        rows = gmd_strings(path)
        if not rows:
            continue
        rel = path.relative_to(eng).as_posix()[:-len('_eng.gmd')] + '_jpn.gmd'
        found = [(i, s) for i, s in enumerate(rows) if s in wanted and s not in keys]
        if not found:
            continue
        for i, s in found:
            keys[s] = (len(files), i)
        cands = ['nativeNX/' + rel, 'nativeNX/jpn/' + rel]
        m = re.fullmatch(r'table/weapon(\d\d)MsgData_jpn\.gmd', rel)
        if m:  # MHXX keeps the weapon names as table/weaponNNMsgData.wNNm
            cands.append(f'nativeNX/table/weapon{m[1]}MsgData.w{m[1]}m')  # (after the patch's _jpn.gmd)
        # The GU Korean patch's own table, when the user copied it in (build.sh does): weapon and armor names
        # the MHXX patch left in Japanese. Read from the user's files only, never shipped. (In the plugin's own
        # folder: a nativeNX/eng folder makes MHXX hang at start.)
        cands.append('nativeNX/plugins/hunters-compendium-ko/' + path.relative_to(eng).as_posix())
        files.append(cands)

    ordered = sorted(keys, key=lambda s: s.encode('utf-8'))
    slot = {s: n for n, s in enumerate(ordered)}
    out = ['// Generated by tools/kor/keys.py from your MHGU dump; local only. English data names that are game text.',
           f'pub const POOL: usize = {sum(len(s.encode()) for s in ordered) * 2 + 65536};',
           'pub static FILES: &[&[&str]] = &[' + ','.join('&[%s]' % ','.join(rust(c) for c in f) for f in files) + '];',
           'pub static KEYS: &[&str] = &[' + ','.join(rust(s) for s in ordered) + '];',
           'pub static BY_FILE: &[&[(u16, u16)]] = &[']
    for f in range(len(files)):
        rows = sorted((i, slot[s]) for s, (ff, i) in keys.items() if ff == f)
        out.append('&[' + ','.join('(%d,%d)' % r for r in rows) + '],')
    out.append('];')
    (GENERATED / 'ko_keys.rs').write_text('\n'.join(out) + '\n', encoding='utf-8')

    sys.path.insert(0, str(ROOT / 'tools/kor'))
    from dict import entries
    rest = sorted(s for s in wanted - set(keys) - set(entries()) if len(s) <= 40 and re.search('[A-Za-z]{2}', s) and '\n' not in s)
    (ROOT / 'build/kor').mkdir(parents=True, exist_ok=True)
    (ROOT / 'build/kor/untranslated.txt').write_text('\n'.join(rest) + '\n', encoding='utf-8')
    print(f'ko_keys.rs: {len(ordered)} game names in {len(files)} GMDs; '
          f'build/kor/untranslated.txt: {len(rest)} other short strings')
    for f in files[:40]:
        print('  ', f[0])
    if len(files) > 40:
        print(f'   ... and {len(files) - 40} more')


if __name__ == '__main__':
    main()
